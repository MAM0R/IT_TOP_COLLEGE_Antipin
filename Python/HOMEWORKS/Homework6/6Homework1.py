"""
Пользователь вводит с клавиатуры размер стороны квадрата.Требуется отобразить на экран заполненный квадрат. Размер стороны равен введённому размеру. 
Например, если пользователь ввёл "3", на экране будет выведено:
***
***
***
"""

x = int(input("Введите размер стороны квадрата: "))

for j in range (x):
    for i in range(x):
        print("*", end="")
    print()