"""
Пользователь вводит с клавиатуры размер стороны квадрата.Требуется отобразить на экране заполненный квадрат(отображаются только границы квадрата). 
Размер стороны равен введённому размеру.
"""

x = int(input("Введите размер стороны квадрата: "))

for j in range (x):
    for i in range(x):
        if j == 0 or j == x - 1 or i == 0 or i == x - 1:
            print("*", end="")
        else:
            print("", end="")
    print()