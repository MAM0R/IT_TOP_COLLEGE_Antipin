day_of_the_week_number = int(input("Введите номер дня недели: "))

if day_of_the_week_number == 1:
    print("День недели: Понедельник")
elif day_of_the_week_number == 2:
    print("День недели: Вторник")
elif day_of_the_week_number == 3:
    print("День недели: Среда")
elif day_of_the_week_number == 4:
    print("День недели: Четверг")
elif day_of_the_week_number == 5:
    print("День недели: Пятница")
elif day_of_the_week_number == 6:
    print("День недели: Суббота")
elif day_of_the_week_number == 7:
    print("День недели: Воскресенье")
else:
    print("Неверный ввод")
                      
