num1 = int(input("Введите 1-ое число: "))
num2 = int(input("Введите 2-ое число: "))
num3 = int(input("Введите 3-ое число: "))

choice = input("Выберите из трёх вариантов: максимум из трёх чисел (команда: max) или минимум из трёх чисел (команда: min) или среднеарифметическое трёх чисел (команда: mid): ")

if choice == "max":
    print("Максимум из трёх чисел:", max(num1, num2, num3))
    
elif choice == "min":
    print("Минимум из трёх чисел:", min(num1, num2, num3))

elif choice == "mid":
    print("Среднеарифметическое трёх чисел:", (num1 + num2 + num3) / 3)

else:
    print("Неверный ввод")
