#Каждый день Хоббит съедает на 20 грамм больше еды, чем в предыдущий день. В первый день Хоббит съел 10 грамм еды. Определите, сколько дней Хоббит будет кушать, чтобы съесть не менее 1000 грамм еды всего в общем за все дни. 

all_food = 10 #сколько всего еды съели
food = 10 #сколько хоббит съедает в день
delta_food = 20 #на сколько хоббит съедает больше 
day = 1

while all_food <= 1000:
    food += delta_food
    all_food += food
    day += 1

print("хоббит округлился на:", day, "день")